"""Generate exact 32x32 Malgun Gothic Bold glyphs used by the firmware UI.

Unicode Hangul syllables are ordered as 19 initials x 21 medials x 28 finals.
The table is keyed by that decomposed syllable index. Rendering a complete
syllable preserves Malgun Gothic Bold's context-dependent component shapes.
"""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "components/ycb_lcd/src/font/malgun_gothic_32.h"
FONT = Path(r"C:\Windows\Fonts\malgunbd.ttf")
SOURCE_DIRS = (ROOT / "main", ROOT / "components")
SOURCE_SUFFIXES = {".c", ".cc", ".cpp", ".h", ".hpp", ".json"}


def used_hangul():
    """Return the complete modern Hangul syllable block used by DY-EP4."""
    return [chr(code) for code in range(0xAC00, 0xD7A4)]


def render_syllable(char):
    canvas = Image.new("L", (128, 128), 0)
    font = ImageFont.truetype(str(FONT), 96)
    ImageDraw.Draw(canvas).text((64, 64), char, font=font, fill=255, anchor="mm")
    bbox = canvas.getbbox()
    output = Image.new("L", (32, 32), 0)
    if bbox is None:
        return output.convert("1")
    glyph = canvas.crop(bbox)
    ratio = min(30 / glyph.width, 30 / glyph.height)
    size = (max(1, round(glyph.width * ratio)),
            max(1, round(glyph.height * ratio)))
    glyph = glyph.resize(size, Image.Resampling.LANCZOS)
    output.paste(glyph, ((32 - size[0]) // 2, (32 - size[1]) // 2))
    return output.point(lambda p: 255 if p >= 112 else 0, mode="1")


def encode(image):
    data = []
    for y in range(32):
        for byte_x in range(4):
            value = 0
            for bit in range(8):
                if image.getpixel((byte_x * 8 + bit, y)):
                    value |= 0x80 >> bit
            data.append(value)
    return data


def main():
    chars = used_hangul()
    lines = [
        "#pragma once",
        "#include <stdint.h>",
        "/* Generated by tools/generate_malgun_kssm32.py. */",
        "#define MALGUN32_FIRST 0xAC00u",
        "#define MALGUN32_LAST  0xD7A3u",
        f"static const uint8_t malgun32_font[{len(chars)}][128] = {{",
    ]
    for char in chars:
        index = ord(char) - 0xAC00
        data = encode(render_syllable(char))
        lines.append(f"    /* U+{ord(char):04X} */ {{")
        for row in range(0, 128, 16):
            lines.append("        " + ",".join(f"0x{x:02X}" for x in data[row:row + 16]) + ",")
        lines.append("    },")
    lines += ["};", ""]
    OUTPUT.write_text("\n".join(lines), encoding="ascii")
    print(f"generated {OUTPUT} ({len(chars)} complete Hangul syllables)")


if __name__ == "__main__":
    main()
